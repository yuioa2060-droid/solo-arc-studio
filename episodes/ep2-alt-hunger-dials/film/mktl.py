# regenerate src/tl.ts from ../voice/marks.json + sections.json (voice starts AT seconds into the film)
import json, re
M = json.load(open('../voice/marks.json')); S = json.load(open('../voice/sections.json')); AT = 1.0
nz = lambda s: re.sub(r"[^a-z0-9'\-]", '', s.lower().replace('’', "'"))
WT = [nz(m['text']) for m in M]; ST = [round(AT + m['start'], 3) for m in M]; EN = [round(AT + m['end'], 3) for m in M]
SEC = {s['name']: round(AT + s['start'], 3) for s in S['sections']}; SEC['hook'] = AT
VEND = EN[-1]; TOTAL = round(VEND + 4.0, 2)
out = f"""// generated by mktl.py from ../voice/marks.json (word times in film seconds; voice starts at AT)
export const AT={AT};
export const WT:string[]={json.dumps(WT)};
export const ST:number[]={json.dumps(ST)};
export const EN:number[]={json.dumps(EN)};
export const SEC:Record<string,number>={json.dumps(SEC)};
export const VEND={VEND};
export const TOTAL={TOTAL};
const nz=(s:string)=>s.toLowerCase().replace(/’/g,"'").replace(/[^a-z0-9'\\-]/g,'');
// index of the first word of phrase (n-th occurrence)
export const idx=(p:string,n=1)=>{{const q=p.split(/\\s+/).map(nz);let c=0;for(let i=0;i<=WT.length-q.length;i++){{let ok=true;for(let j=0;j<q.length;j++)if(WT[i+j]!==q[j]){{ok=false;break;}}if(ok&&++c===n)return i;}}throw new Error('phrase not found: '+p);}};
export const t=(p:string,n=1)=>ST[idx(p,n)];
export const te=(p:string,n=1)=>EN[idx(p,n)+p.split(/\\s+/).length-1];
"""
open('src/tl.ts', 'w').write(out)
print(SEC, VEND, TOTAL)
